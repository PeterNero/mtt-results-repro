def outer_sum(rows: list[tuple[int, int]]) -> sp.Matrix:
    result = sp.zeros(2)
    for row in rows:
        vector = sp.Matrix(row)
        result += vector * vector.T
    return result


def integrate_ch2_matrix(matrix: sp.Matrix, intersection: sp.Matrix) -> sp.Rational:
    # ch2 = (1/2) C_ab H_a H_b, with both off-diagonal entries present.
    return sp.Rational(1, 2) * sum(
        matrix[a, b] * intersection[a, b] for a in range(2) for b in range(2)
    )


def matrix_rows(matrix: sp.Matrix) -> list[list[int]]:
    return [[int(value) for value in row] for row in matrix.tolist()]


